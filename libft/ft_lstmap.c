#include "libft.h"

t_list	*ft_lstmap(t_list *lst, void *(*f)(void *), void (*del)(void *))
{
	t_list	*head;
	t_list	*new;

	head = NULL;
	while (lst)
	{
		new = ft_lstnew(f(lst->content));
		if (!new->content)
		{
			del(new->content);
			free(new);
		}
		ft_lstadd_back(&head, new);
		lst = lst->next;
	}
	return (head);
}
